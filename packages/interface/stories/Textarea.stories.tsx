import type { Meta, StoryObj } from '@storybook/react'
import { fn } from 'storybook/test'
import { Textarea } from '../src/controls/inputs'
import { describeComponent } from './support/describe'
import { Column, Item, Row } from './support/layout'

const meta = {
  title: 'Controls/Textarea',
  component: Textarea,
  tags: ['autodocs'],
  parameters: describeComponent({
    summary: '多行文本输入，样式与 `Input` 一致。',
    use: ['描述、备注、脚本片段等多行文字'],
    avoid: ['单行文字 → 用 `Input`'],
    related: ['`Input`：单行', '`PropertyField` 的 `widget="textarea"`：多行属性，Ctrl/⌘ + Enter 提交'],
  }),
  args: { 'aria-label': 'Description', placeholder: 'Describe the object', rows: 3, onValueChange: fn() },
} satisfies Meta<typeof Textarea>
export default meta
type Story = StoryObj<typeof meta>

export const Basic: Story = {
  render: (args) => (
    <Column width={320}>
      <Textarea {...args} />
    </Column>
  ),
}

/** 与 `Input` 相同的三种外观。 */
export const Variants: Story = {
  render: (args) => (
    <Row>
      {(['soft', 'outline', 'subtle'] as const).map((variant) => (
        <Item key={variant} label={variant}>
          <Textarea {...args} variant={variant} defaultValue={'Line one\nLine two'} />
        </Item>
      ))}
    </Row>
  ),
}

/** 只有两档：`sm` 用于面板，`md` 用于表单。 */
export const Sizes: Story = {
  render: (args) => (
    <Row>
      {(['sm', 'md'] as const).map((size) => (
        <Item key={size} label={size}>
          <Textarea {...args} size={size} defaultValue="Notes" />
        </Item>
      ))}
    </Row>
  ),
}

/** 校验、只读和禁用。 */
export const States: Story = {
  render: (args) => (
    <Row>
      <Item label="invalid">
        <Textarea {...args} state="invalid" defaultValue="Too long" aria-invalid />
      </Item>
      <Item label="readOnly">
        <Textarea {...args} readOnly defaultValue="Generated by the importer" />
      </Item>
      <Item label="disabled">
        <Textarea {...args} disabled defaultValue="Unavailable" />
      </Item>
    </Row>
  ),
}
